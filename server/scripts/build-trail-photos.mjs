// Turns reviewed picks into data/trail-photos.json (source of truth, committed),
// downloads two sizes into scripts/photos/out/, and writes seed/trail-covers.sql.
//   node scripts/build-trail-photos.mjs
// Then upload with scripts/upload-trail-photos.sh and run the SQL against D1.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'scripts', 'photos');
const UA = 'TrailingApp/1.0 (https://trailing.pages.dev; trail cover photos)';
const cands = JSON.parse(fs.readFileSync(path.join(dir, 'candidates.json'), 'utf8'));
const picks = JSON.parse(fs.readFileSync(path.join(dir, 'picks.json'), 'utf8'));
const REUSE = { 'mount-timpanogos-aspen-grove': 'mount-timpanogos-timpooneke' };

const lit = (v) => (v == null ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const clean = (s, n) => (s || '').replace(/\s+/g, ' ').replace(/^(Photo by|By)\s+/i, '').trim().slice(0, n) || null;

const out = path.join(dir, 'out');
fs.mkdirSync(out, { recursive: true });
const photos = {};
for (const [slug, i] of Object.entries(picks)) {
  const p = cands[slug].reviewable[i];
  photos[slug] = {
    file: p.title, page: p.page, author: clean(p.author, 80), license: p.license.trim(), license_url: p.license_url,
    thumb_base: p.thumb,
  };
}
for (const [slug, from] of Object.entries(REUSE)) photos[slug] = { ...photos[from] };

async function download(url, file) {
  if (fs.existsSync(file)) return;
  for (let a = 0; a < 5; a++) {
    const res = await fetch(url, { headers: { 'User-Agent': UA } });
    if (res.ok) { fs.writeFileSync(file, Buffer.from(await res.arrayBuffer())); return; }
    if (res.status !== 429 && res.status < 500) throw new Error(`${res.status} ${url}`);
    await new Promise((r) => setTimeout(r, 2500 * (a + 1)));
  }
  throw new Error(`gave up ${url}`);
}

const sql = ['-- Generated by scripts/build-trail-photos.mjs — openly licensed covers from Wikimedia Commons.'];
for (const [slug, ph] of Object.entries(photos)) {
  // Wikimedia serves standard widths only (500, 960, 1280, 1920, …).
  const big = ph.thumb_base.replace(/\/\d+px-/, '/1280px-').replace(/\?.*$/, '');
  const small = ph.thumb_base.replace(/\/\d+px-/, '/500px-').replace(/\?.*$/, '');
  await download(big, path.join(out, `cover-${slug}.jpg`));
  await download(small, path.join(out, `cover-${slug}-sm.jpg`));
  await new Promise((r) => setTimeout(r, 250));
  sql.push(`INSERT INTO trail_covers (trail_id, url, url_small, author, license, license_url, source_url)
  SELECT id, ${lit(`/uploads/cover-${slug}.jpg`)}, ${lit(`/uploads/cover-${slug}-sm.jpg`)}, ${lit(ph.author)}, ${lit(ph.license)}, ${lit(ph.license_url)}, ${lit(ph.page)}
  FROM trails WHERE slug = ${lit(slug)}
  ON CONFLICT(trail_id) DO UPDATE SET url=excluded.url, url_small=excluded.url_small, author=excluded.author,
  license=excluded.license, license_url=excluded.license_url, source_url=excluded.source_url, updated_at=datetime('now');`);
  delete ph.thumb_base;
}
fs.writeFileSync(path.join(root, 'data', 'trail-photos.json'), JSON.stringify(photos, null, 2));
fs.writeFileSync(path.join(root, 'seed', 'trail-covers.sql'), sql.join('\n') + '\n');
console.log(`${Object.keys(photos).length} trail photos → scripts/photos/out, data/trail-photos.json, seed/trail-covers.sql`);
