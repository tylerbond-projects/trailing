// Compiles every data/regions/*.json file into seed/trails.sql — idempotent
// upserts keyed by slug. Run it against D1 after adding or editing a region:
//   npm run db:trails:local   |   npm run db:trails:remote
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { difficultyScore, difficultyLabel, estimatedMinutes } from '../src/difficulty.js';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'data', 'regions');
const lit = (v) => (v == null ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);

const out = ['-- Generated by scripts/build-trails-sql.mjs — do not edit by hand.'];
let count = 0;
for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
  const { region, trails } = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'));
  out.push(`INSERT INTO regions (id, name, state, country, center_lat, center_lng, zoom) VALUES (${[
    region.id, region.name, region.state, region.country, region.center?.[0], region.center?.[1], region.zoom ?? 10].map(lit).join(', ')})
  ON CONFLICT(id) DO UPDATE SET name=excluded.name, state=excluded.state, country=excluded.country,
  center_lat=excluded.center_lat, center_lng=excluded.center_lng, zoom=excluded.zoom;`);
  for (const t of trails) {
    const score = t.difficulty_score ?? difficultyScore(t);
    const vals = [
      t.slug, region.id, t.name, t.area, t.description ?? '', t.tips, t.lat, t.lng, t.distance_mi, t.elevation_gain_ft,
      t.max_elevation_ft, t.route_type, score, difficultyLabel(score), estimatedMinutes(t),
      JSON.stringify(t.features ?? []), JSON.stringify(t.activities ?? ['hike']), JSON.stringify(t.best_seasons ?? []),
      t.dogs, t.kid_friendly == null ? null : Number(t.kid_friendly), Number(!!t.technical), t.surface, t.fee, t.permit,
    ];
    out.push(`INSERT INTO trails (slug, region_id, name, area, description, tips, lat, lng, distance_mi, elevation_gain_ft,
  max_elevation_ft, route_type, difficulty_score, difficulty_label, est_minutes, features, activities, best_seasons, dogs,
  kid_friendly, technical, surface, fee, permit) VALUES (${vals.map(lit).join(', ')})
  ON CONFLICT(slug) DO UPDATE SET region_id=excluded.region_id, name=excluded.name, area=excluded.area,
  description=excluded.description, tips=excluded.tips, lat=excluded.lat, lng=excluded.lng, distance_mi=excluded.distance_mi,
  elevation_gain_ft=excluded.elevation_gain_ft, max_elevation_ft=excluded.max_elevation_ft, route_type=excluded.route_type,
  difficulty_score=excluded.difficulty_score, difficulty_label=excluded.difficulty_label, est_minutes=excluded.est_minutes,
  features=excluded.features, activities=excluded.activities, best_seasons=excluded.best_seasons, dogs=excluded.dogs,
  kid_friendly=excluded.kid_friendly, technical=excluded.technical, surface=excluded.surface, fee=excluded.fee, permit=excluded.permit;`);
    count++;
  }
}
fs.mkdirSync(path.join(root, 'seed'), { recursive: true });
fs.writeFileSync(path.join(root, 'seed', 'trails.sql'), out.join('\n') + '\n');
console.log(`Wrote seed/trails.sql (${count} trails)`);
